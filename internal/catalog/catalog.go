// Package catalog answers ONE question: which preset of a given slicer is the
// machine the author named?
//
// It exists because a preset name belongs to a slicer's catalogue, not to the
// machine. The canonical says "Bambu Lab P2S, 0.6"; Orca wants the exact string
// "Bambu Lab P2S 0.6 nozzle" and PrusaSlicer wants printer_model=="MINI" — two
// spellings of one fact, neither of which has any business in a canonical file
// (docs/mapping.md pitfall #13).
//
// The data is a dated SNAPSHOT of both upstream catalogues, regenerated by
// cmd/aldina-catalog and committed like a golden file. Nothing here touches the
// network, so a machine released after the last regeneration is unknown — and
// says so, loudly.
//
// This package imports neither canonical nor any provider: it is pure data plus
// lookup, and takes plain (model, nozzle) arguments.
package catalog

import (
	_ "embed"
	"encoding/json"
	"errors"
	"fmt"
	"slices"
	"strconv"
	"strings"
	"sync"
)

//go:embed catalog.json
var catalogJSON []byte

//go:embed aliases.json
var aliasesJSON []byte

// Machine is one entry: a model, a nozzle, and how each slicer names it.
type Machine struct {
	Model string `json:"model"`
	// ModelID is what a Prusa `printer_model==` clause compares against.
	// Empty for Orca, which binds by preset name and has no such id.
	ModelID string  `json:"model_id,omitempty"`
	Nozzle  float64 `json:"nozzle"`
	// Variant is the slicer's printer_variant verbatim. It usually spells the
	// nozzle diameter and nothing else, but ~30% of Prusa's variants (and a
	// handful of Orca's) also encode a HOTEND CLASS: "HF0.4"/"0.4HF" (high
	// flow), "volcano 0.6", "0.4HS", "0.4+0.6" (two nozzles).
	//
	// The canonical has no word for that yet, so those entries resolve to an
	// error naming them rather than to a preset — see plainVariant. They stay
	// in the index precisely so the error can list them: dropping them at
	// generation would have made a whole class of machine quietly untargetable,
	// which is the failure this package exists to prevent.
	Variant string `json:"variant"`
	// Presets holds EVERY preset sharing this model and nozzle. Usually one;
	// a handful of vendors ship several (Raise3D Left/Right/Dual, Volumic
	// COPY/MIRROR MODE, Prusa MMU Single). Callers that bind by name emit them
	// all — the filament holds for every variant of the same hardware.
	Presets []string `json:"presets"`
}

// Snapshot is the whole file. It is exported because cmd/aldina-catalog writes
// it: one definition of the format, on the side that reads it, rather than a
// mirror in the generator to keep in sync by hand.
//
// Field order is part of the contract — it decides the key order in the
// committed JSON, and a reordering would show up as a whole-file diff hiding
// the real change. TestSnapshotRoundTripsByteForByte guards it.
type Snapshot struct {
	// Source is provenance: which commit of which repository this was cut
	// from, and when. Nothing here reads it — it exists so a human can tell
	// how old the snapshot is, and the generator fills it.
	Source map[string]Source `json:"source"`
	Orca   []Machine         `json:"orca"`
	Prusa  []Machine         `json:"prusa"`
}

type Source struct {
	Repo    string `json:"repo"`
	Ref     string `json:"ref"`
	Commit  string `json:"commit"`
	Fetched string `json:"fetched"`
}

type aliasFile struct {
	Aliases []struct {
		Orca  string `json:"orca"`
		Prusa string `json:"prusa"`
	} `json:"aliases"`
}

// Slicer names the catalogue being queried. It is not a provider interface —
// just a label, so an error can say which base failed to answer.
type Slicer string

const (
	Orca  Slicer = "orca"
	Prusa Slicer = "prusa"
)

type index struct {
	byModel map[Slicer]map[string][]Machine
	// byPreset reverses byModel for the ingest direction: a preset name maps
	// back to the machine that owns it.
	byPreset map[Slicer]map[string]Machine
	// alias maps a model name to its counterpart in the other catalogue.
	alias map[string]string
	// pairs keeps aliases.json in file order, for the tests that check it
	// against the catalogue. A map cannot: it is symmetric, so it no longer
	// says which side is which.
	pairs [][2]string
}

// loaded parses the embedded snapshot once. A malformed embed is a build-time
// mistake, not a runtime condition: there is no sane way to continue, so it
// panics — the one case CONTRIBUTING.md allows (a proven internal bug).
var loaded = sync.OnceValue(func() *index {
	var snap Snapshot
	if err := json.Unmarshal(catalogJSON, &snap); err != nil {
		panic("catalog: malformed catalog.json: " + err.Error())
	}
	var aliases aliasFile
	if err := json.Unmarshal(aliasesJSON, &aliases); err != nil {
		panic("catalog: malformed aliases.json: " + err.Error())
	}

	idx := &index{
		byModel: map[Slicer]map[string][]Machine{
			Orca:  make(map[string][]Machine),
			Prusa: make(map[string][]Machine),
		},
		byPreset: map[Slicer]map[string]Machine{
			Orca:  make(map[string]Machine),
			Prusa: make(map[string]Machine),
		},
		alias: make(map[string]string, 2*len(aliases.Aliases)),
	}
	for _, m := range snap.Orca {
		idx.byModel[Orca][m.Model] = append(idx.byModel[Orca][m.Model], m)
		for _, p := range m.Presets {
			idx.byPreset[Orca][p] = m
		}
	}
	for _, m := range snap.Prusa {
		idx.byModel[Prusa][m.Model] = append(idx.byModel[Prusa][m.Model], m)
		for _, p := range m.Presets {
			idx.byPreset[Prusa][p] = m
		}
	}
	// Equivalence is symmetric: the author may write either spelling.
	for _, a := range aliases.Aliases {
		idx.alias[a.Orca] = a.Prusa
		idx.alias[a.Prusa] = a.Orca
		idx.pairs = append(idx.pairs, [2]string{a.Orca, a.Prusa})
	}
	return idx
})

// Lookup resolves (model, nozzleMM) in one slicer's catalogue.
//
// Resolution is exact first, then through the alias table — never fuzzy. A
// near-miss that silently binds the wrong hardware is worse than an error, and
// the error is the only thing that makes a missing alias visible.
//
// Errors describe the CATALOGUE failure and nothing else. Naming the canonical
// field that led here is the caller's job: this package does not know what a
// compat.machines is, and both providers already wrap with %w.
func Lookup(s Slicer, model string, nozzleMM float64) (Machine, error) {
	idx := loaded()
	byModel, ok := idx.byModel[s]
	if !ok {
		return Machine{}, fmt.Errorf("unknown slicer %q", s)
	}
	// Guarded here rather than in each provider: an empty model would otherwise
	// fall through to "in neither catalogue", which is true but useless.
	if model == "" {
		return Machine{}, errors.New("model is required")
	}
	if nozzleMM <= 0 {
		return Machine{}, fmt.Errorf("nozzle must be positive, got %s", formatNozzle(nozzleMM))
	}

	entries, found := byModel[model]
	if !found {
		if other, ok := idx.alias[model]; ok {
			entries, found = byModel[other]
		}
	}
	if !found {
		return Machine{}, unknownModelError(idx, s, model)
	}

	var decorated []string
	for _, m := range entries {
		if m.Nozzle != nozzleMM {
			continue
		}
		if m.plainVariant() {
			return m, nil
		}
		decorated = append(decorated, m.Variant)
	}
	// The diameter matches, but only on hotend variants we cannot yet name.
	// Silently picking one would bind a high-flow filament to a stock hotend.
	if len(decorated) > 0 {
		slices.Sort(decorated)
		return Machine{}, fmt.Errorf("%s has %q with a %s mm nozzle only as %s, "+
			"a hotend class the canonical format cannot express yet",
			s, model, formatNozzle(nozzleMM), strings.Join(decorated, "/"))
	}
	return Machine{}, fmt.Errorf("%s knows %q but not with a %s mm nozzle (available: %s)",
		s, model, formatNozzle(nozzleMM), joinNozzles(entries))
}

// plainVariant reports whether printer_variant says only "this diameter". A
// decorated one ("HF0.4", "volcano 0.6") names hardware the canonical has no
// field for, so it must not answer a plain (model, nozzle) query.
//
// Parsed, not compared as text: Prusa writes "0.50" where we would format
// "0.5", and a string comparison would call that decorated.
func (m Machine) plainVariant() bool {
	if m.Variant == "" {
		return true
	}
	_, err := strconv.ParseFloat(m.Variant, 64)
	return err == nil
}

// unknownModelError distinguishes the two ways a model can be unknown, because
// the fix differs: a typo is the author's, an absent machine is the slicer's.
// The second case is the common one — most models exist in only one catalogue.
func unknownModelError(idx *index, s Slicer, model string) error {
	other := Orca
	if s == Orca {
		other = Prusa
	}
	if _, ok := idx.byModel[other][model]; ok {
		return fmt.Errorf("%q is known to %s but absent from %s's catalogue, "+
			"so it cannot be targeted on %s", model, other, s, s)
	}
	return fmt.Errorf("%q is in neither catalogue (checked %s): "+
		"check the spelling against the slicer's printer list, or regenerate the "+
		"snapshot with `go run ./cmd/aldina-catalog` if the machine is newer than it", model, s)
}

// LookupPreset resolves a preset name back to its machine. It is the ingest
// direction of Lookup: where Lookup answers "which preset names this machine",
// LookupPreset answers "which machine owns this preset name". The second return
// is false when the name is in no preset list.
func LookupPreset(s Slicer, preset string) (Machine, bool) {
	idx := loaded()
	m, ok := idx.byPreset[s][preset]
	return m, ok
}

// Models lists every model name known to a slicer, sorted. Used by the tests
// that keep aliases.json honest.
func Models(s Slicer) []string {
	idx := loaded()
	out := make([]string, 0, len(idx.byModel[s]))
	for model := range idx.byModel[s] {
		out = append(out, model)
	}
	slices.Sort(out)
	return out
}

// Aliases returns the curated equivalence pairs (orca name, prusa name).
func Aliases() [][2]string { return loaded().pairs }

func formatNozzle(mm float64) string { return strconv.FormatFloat(mm, 'g', -1, 64) }

// joinNozzles lists the diameters a model is available in — deduplicated,
// because one diameter often appears under several hotend variants.
func joinNozzles(entries []Machine) string {
	sizes := make([]float64, len(entries))
	for i, m := range entries {
		sizes[i] = m.Nozzle
	}
	slices.Sort(sizes)
	labels := make([]string, 0, len(sizes))
	for _, mm := range slices.Compact(sizes) {
		labels = append(labels, formatNozzle(mm))
	}
	return strings.Join(labels, ", ")
}
