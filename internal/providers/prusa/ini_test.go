// Every expectation here was measured on PrusaSlicer 2.9.6 via --load/--save,
// or read off references/prusa/ (repaired). None is inferred from a generic
// idea of what INI looks like.
func TestEscapeCStyle(t *testing.T) {
	cases := []struct{ name, in, want string }{
		{"plain", "M900 K0.2", "M900 K0.2"},
		{"newline becomes two chars", "line one\nline two", `line one\nline two`},
		{"carriage return", "a\rb", `a\rb`},
		{"backslash doubles", `C:\temp`, `C:\\temp`},
		// A scalar keeps ';' and '"' bare: real exports carry
		// `start_gcode = M17 ; enable steppers` and `M862.3 P "XL"` unquoted.
		{"semicolon stays bare", "M17 ; enable steppers", "M17 ; enable steppers"},
		{"double quote stays bare", `M862.3 P "XL"`, `M862.3 P "XL"`},
		{"empty", "", ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := escapeCStyle(c.in); got != c.want {
				t.Errorf("escapeCStyle(%q) = %q, want %q", c.in, got, c.want)
			}
		})
	}
}

func TestEscapeStrings(t *testing.T) {
	cases := []struct {
		name string
		in   []string
		want string
	}{
		// The reason filament_settings_id is a list: a scalar cannot express
		// "one empty element", and the real export shows `= ""`.
		{"sole empty item is quoted", []string{""}, `""`},
		{"plain item unquoted", []string{"PET"}, "PET"},
		{"a space forces quotes", []string{"Forward AM"}, `"Forward AM"`},
		{"a semicolon forces quotes", []string{"; Filament-specific end gcode"}, `"; Filament-specific end gcode"`},
		{"newline forces quotes and escapes", []string{"line one\nline two"}, `"line one\nline two"`},
		{"inner quote is backslash-escaped", []string{`M862.3 P "XL"`}, `"M862.3 P \"XL\""`},
		{"several items join on ;", []string{"a", "b"}, "a;b"},
		// Empty is only quoted when it is the SOLE item; among others it is
		// simply an empty slot, exactly as unescape_strings_cstyle reads it.
		{"empty among others stays bare", []string{"a", ""}, "a;"},
		{"no items", []string{}, ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := escapeStrings(c.in); got != c.want {
				t.Errorf("escapeStrings(%q) = %q, want %q", c.in, got, c.want)
			}
		})
	}
}

// '#' must survive bare. It is the character that corrupted the reference
// files, and a stock INI writer backtick-quotes it.
func TestColourHashSurvivesBare(t *testing.T) {
	out := mustMarshal(t, FilamentSettings{
		FilamentIdentity: FilamentIdentity{FilamentColour: "#F7F7F7"},
	})
	if !strings.Contains(out, "filament_colour = #F7F7F7\n") {
		t.Errorf("colour was altered:\n%s", out)
	}
}

// Absence is omission: an unset field must leave no key at all, so the slicer
// keeps its own default. Same rule as the canonical pointers.
func TestUnsetFieldsAreOmitted(t *testing.T) {
	out := mustMarshal(t, FilamentSettings{
		FilamentTemp: FilamentTemp{Temperature: []string{"215"}},
	})
	if !strings.Contains(out, "temperature = 215\n") {
		t.Fatalf("temperature missing:\n%s", out)
	}
	for _, absent := range []string{"filament_vendor", "bed_temperature", "filament_notes"} {
		if strings.Contains(out, absent) {
			t.Errorf("%s must be omitted when unset:\n%s", absent, out)
		}
	}
}

// One line per key, keys sorted: the shape of every real export (85 keys,
// 86 physical lines).
func TestLayout(t *testing.T) {
	out := mustMarshal(t, FilamentSettings{
		FilamentTemp:     FilamentTemp{Temperature: []string{"215"}, BedTemperature: []string{"70"}},
		FilamentIdentity: FilamentIdentity{FilamentVendor: "Forward AM"},
	})
	keys := strings.Split(strings.TrimSuffix(out, "\n"), "\n")
	if len(keys) != 3 {
		t.Fatalf("got %d key lines, want 3:\n%s", len(keys), out)
	}
	for i := 1; i < len(keys); i++ {
		if keys[i-1] >= keys[i] {
			t.Errorf("keys not sorted: %q before %q", keys[i-1], keys[i])
		}
	}
}

// The section header is the difference between "a filament preset" and "a
// whole configuration". Without it PrusaSlicer adopts the file as the print
// AND the filament AND the printer at once — observed on 2.9.6, all three
// slots in PrusaSlicer.ini pointing at the same imported file.
func TestBundleCarriesTheSectionHeader(t *testing.T) {
	raw, err := MarshalBundle("filament", "Overture PETG", FilamentSettings{
		FilamentTemp: FilamentTemp{Temperature: []string{"240"}},
	})
	if err != nil {
		t.Fatalf("MarshalBundle: %v", err)
	}
	lines := strings.Split(strings.TrimSuffix(string(raw), "\n"), "\n")
	if lines[0] != "# generated by aldina" {
		t.Errorf("line 1 = %q, want the provenance comment", lines[0])
	}
	if lines[1] != "[filament:Overture PETG]" {
		t.Errorf("line 2 = %q, want the section header", lines[1])
	}
	// Exactly ONE section: a second one would make the import touch another
	// category, which is the bug this shape exists to prevent.
	if n := strings.Count(string(raw), "["); n != 1 {
		t.Errorf("found %d section headers, want exactly 1:\n%s", n, raw)
	}
	// No [presets] block: sharing a filament must never switch the recipient's
	// printer or print profile.
	if strings.Contains(string(raw), "[presets]") {
		t.Errorf("bundle must not select active presets:\n%s", raw)
	}
}

func TestBundleNeedsSectionAndName(t *testing.T) {
	for _, c := range []struct{ section, name string }{{"", "X"}, {"filament", ""}} {
		if _, err := MarshalBundle(c.section, c.name, FilamentSettings{}); err == nil {
			t.Errorf("MarshalBundle(%q, %q) must fail", c.section, c.name)
		}
	}
}

// A gcode blob carrying BOTH a semicolon and a newline is the worst realistic
// case, and the one PrusaSlicer mis-parses when it is not quoted.
func TestGcodeBlobRoundTripShape(t *testing.T) {
	out := mustMarshal(t, FilamentSettings{
		FilamentGcode: FilamentGcode{
			StartFilamentGcode: []string{"M900 K0.2 ; set K\nG92 E0"},
		},
	})
	want := `start_filament_gcode = "M900 K0.2 ; set K\nG92 E0"` + "\n"
	if !strings.Contains(out, want) {
		t.Errorf("got:\n%s\nwant to contain:\n%s", out, want)
	}
}

func TestMarshalRejectsNonStruct(t *testing.T) {
	if _, err := marshalBody("not a struct"); err == nil {
		t.Error("Marshal on a string must fail")
	}
}

func mustMarshal(t *testing.T, s FilamentSettings) string {
	t.Helper()
	raw, err := marshalBody(s)
	if err != nil {
		t.Fatalf("Marshal: %v", err)
	}
	return string(raw)
}
