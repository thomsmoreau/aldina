package prusa

// ini.go — writer for PrusaSlicer's INI dialect.
//
// It is NOT generic INI, and a stock library gets it wrong: values may start
// with '#' (filament_colour = #F7F7F7), may contain unquoted spaces
// (filament_vendor = Forward AM) and unquoted double quotes
// (M862.3 P "XL"). See references/prusa/README.md.
//
// The escaping below is not invented. It mirrors escape_string_cstyle and
// escape_strings_cstyle in PrusaSlicer's src/libslic3r/Config.cpp, and was
// confirmed on 2.9.6 by feeding values through --load/--save: what comes back
// is byte-identical to what goes in (conform_test.go).
//
// Two encodings, chosen by the Go type — that is the whole design:
//
//	string    → ConfigOptionString: escaped, NEVER quoted. A space in the
//	            value stays bare, which is why filament_vendor cannot be a list.
//	[]string  → ConfigOptionStrings: items joined by ';', each quoted only when
//	            it has to be. A per-extruder array in a config bundle; a single
//	            element in the detached export we render.
//
// Layout is one line per key, keys sorted: no multi-line values, no sections
// (a detached filament export carries no [filament:...] header).

import (
	"fmt"
	"reflect"
	"slices"
	"strings"
)

// escapeCStyle escapes the three characters that cannot survive a one-line
// value. Deliberately NOT escaping '"' or ';': an unquoted PrusaSlicer scalar
// carries them raw, and adding backslashes would corrupt gcode.
func escapeCStyle(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	for i := 0; i < len(s); i++ {
		switch c := s[i]; c {
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		default:
			b.WriteByte(c)
		}
	}
	return b.String()
}

// itemNeedsQuotes reports whether one element of a string LIST must be quoted.
// Straight from escape_strings_cstyle: any of these characters would otherwise
// end the item (';' is the separator) or break the line. A lone empty item is
// quoted too, else the key would read as "no elements" rather than "one empty
// element" — that is why real exports show filament_settings_id = "".
func itemNeedsQuotes(item string, sole bool) bool {
	if sole && item == "" {
		return true
	}
	return strings.ContainsAny(item, " ;\t\\\"\r\n")
}

// escapeStrings renders a string LIST. Inside quotes '"' and '\' are
// backslash-escaped on top of the newline escaping.
func escapeStrings(items []string) string {
	parts := make([]string, len(items))
	for i, item := range items {
		if !itemNeedsQuotes(item, len(items) == 1) {
			parts[i] = escapeCStyle(item)
			continue
		}
		esc := escapeCStyle(item)
		esc = strings.ReplaceAll(esc, `"`, `\"`)
		parts[i] = `"` + esc + `"`
	}
	return strings.Join(parts, ";")
}

// MarshalBundle renders one preset as a PrusaSlicer CONFIG BUNDLE.
//
// The section header is not decoration, it is what makes the file a preset
// rather than a whole configuration. A flat headerless INI is a FULL CONFIG:
// importing one makes PrusaSlicer adopt it as the print AND the filament AND
// the printer at once, all three named after the file. Verified on 2.9.6 —
// PrusaSlicer.ini came back with the same file selected in all three slots.
//
// With `[filament:NAME]` the file is a bundle, PrusaSlicer installs it in that
// category alone, and the NAME comes from the header. That is also why
// filament_settings_id is left empty in a bundle: the header already carries
// the identity (references/prusa/PrusaSlicer_config_bundle.ini).
//
// A `[presets]` section — which names the ACTIVE selection — is deliberately
// omitted: sharing a filament must not silently switch the recipient's printer
// or print profile. PresetBundle::load_configbundle does not require it.
//
// section is the bundle category ("filament", "print", "printer").
func MarshalBundle(section, presetName string, v any) ([]byte, error) {
	if section == "" || presetName == "" {
		return nil, fmt.Errorf("prusa: bundle needs a section and a preset name, got %q/%q", section, presetName)
	}
	body, err := marshalBody(v)
	if err != nil {
		return nil, err
	}
	return append([]byte("# generated by aldina\n["+section+":"+presetName+"]\n"), body...), nil
}

// marshalBody renders the flat `key = value` block, sorted.
//
// Absence is omission: a nil slice or an empty string means "not set", the key
// is left out, and the slicer keeps its own default. That mirrors the canonical
// pointer rule — we never write a key to say nothing.
//
// Kept separate from MarshalBundle because the bundle is only a category
// header over this body: the header decides where PrusaSlicer installs the
// preset, the body carries every value. Verified against PrusaSlicer 2.9.6:
// the GUI import and `--load` both accept the bundled `[filament:NAME]` form.
func marshalBody(v any) ([]byte, error) {
	lines := make([]string, 0, 96)
	if err := collect(reflect.ValueOf(v), &lines); err != nil {
		return nil, err
	}
	slices.Sort(lines)

	var b strings.Builder
	for _, line := range lines {
		b.WriteString(line)
		b.WriteByte('\n')
	}
	return []byte(b.String()), nil
}

// collect walks the embedded groups. The groups exist for readability only —
// the wire form is flat, so they are flattened here rather than in the schema.
func collect(v reflect.Value, lines *[]string) error {
	if v.Kind() == reflect.Pointer {
		v = v.Elem()
	}
	if v.Kind() != reflect.Struct {
		return fmt.Errorf("prusa: marshal expects a struct, got %s", v.Kind())
	}

	t := v.Type()
	for i := range t.NumField() {
		field, value := t.Field(i), v.Field(i)
		if field.Anonymous {
			if err := collect(value, lines); err != nil {
				return err
			}
			continue
		}
		key := field.Tag.Get("ini")
		if key == "" {
			return fmt.Errorf("prusa: %s.%s has no ini tag", t.Name(), field.Name)
		}

		switch value.Kind() {
		case reflect.String:
			if s := value.String(); s != "" {
				*lines = append(*lines, key+" = "+escapeCStyle(s))
			}
		case reflect.Slice:
			if value.IsNil() {
				continue
			}
			items, ok := value.Interface().([]string)
			if !ok {
				return fmt.Errorf("prusa: %s.%s must be []string", t.Name(), field.Name)
			}
			*lines = append(*lines, key+" = "+escapeStrings(items))
		default:
			return fmt.Errorf("prusa: %s.%s has unsupported kind %s", t.Name(), field.Name, value.Kind())
		}
	}
	return nil
}
